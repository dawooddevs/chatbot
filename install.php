<?php
/**
 * One-page installer. Delete this file once the panel is running.
 */
declare(strict_types=1);

define('INSTALLER', true);
require __DIR__ . '/app/bootstrap.php';

use App\Auth;
use App\Config;
use App\Database;
use App\Schema;
use App\Settings;

// Password provisioned for the first account. It is a bcrypt hash, so the
// plain password is never stored in the source tree.
const SEEDED_ADMIN_USERNAME = 'Dawood';
const SEEDED_ADMIN_HASH = '$2y$12$NNPgJd47rTATk/q/yJUfH.jBnxAAZz/7lE7j33FWTzazpdhzLM/v6';

$configPath = APP_DIR . '/config.php';
$alreadyInstalled = is_file($configPath);

$checks = [
    'PHP 8.0 or newer' => [PHP_VERSION_ID >= 80000, PHP_VERSION],
    'pdo_mysql extension' => [extension_loaded('pdo_mysql'), 'required for MySQL'],
    'mbstring extension' => [extension_loaded('mbstring'), 'required for text handling'],
    'json extension' => [extension_loaded('json'), 'required'],
    'Outbound HTTPS (curl or allow_url_fopen)' => [
        function_exists('curl_init') || filter_var(ini_get('allow_url_fopen'), FILTER_VALIDATE_BOOL),
        'required to reach api.openai.com',
    ],
    'app/ directory writable' => [is_writable(APP_DIR), APP_DIR],
    'storage/logs writable' => [is_writable(APP_ROOT . '/storage/logs'), APP_ROOT . '/storage/logs'],
];
$checksPass = !in_array(false, array_map(static fn (array $c): bool => (bool)$c[0], $checks), true);

$guessedBase = (function (): string {
    $scheme = App\Session::isHttps() ? 'https' : 'http';
    $host = $_SERVER['HTTP_HOST'] ?? 'localhost';
    $dir = rtrim(str_replace('\\', '/', dirname((string)($_SERVER['SCRIPT_NAME'] ?? '/'))), '/');
    return $scheme . '://' . $host . $dir;
})();

$errors = [];
$done = false;

if ($_SERVER['REQUEST_METHOD'] === 'POST' && !$alreadyInstalled) {
    $db = [
        'host' => (string)post('db_host', 'localhost'),
        'name' => (string)post('db_name', ''),
        'user' => (string)post('db_user', ''),
        'pass' => (string)($_POST['db_pass'] ?? ''),
        'port' => (int)post('db_port', '3306'),
    ];
    $baseUrl = rtrim((string)post('base_url', $guessedBase), '/');
    $username = (string)post('admin_username', SEEDED_ADMIN_USERNAME);
    $password = (string)($_POST['admin_password'] ?? '');
    $email = post('admin_email') ?: null;

    if ($db['name'] === '' || $db['user'] === '') {
        $errors[] = 'Enter the database name and user you created in cPanel.';
    }
    if ($username === '') {
        $errors[] = 'Enter an admin username.';
    }
    if ($password !== '' && strlen($password) < 10) {
        $errors[] = 'The admin password must be at least 10 characters.';
    }
    if ($password === '' && $username !== SEEDED_ADMIN_USERNAME) {
        $errors[] = 'Enter a password for the admin account.';
    }

    if ($errors === []) {
        try {
            $pdo = Database::connect($db);
            Database::setPdo($pdo);
            Schema::migrate($pdo);

            $config = [
                'db' => $db,
                'base_url' => $baseUrl,
                'app_key' => bin2hex(random_bytes(32)),
                'session_name' => 'chatbotsid',
                'debug' => false,
            ];
            $written = file_put_contents(
                $configPath,
                "<?php\n// Generated by install.php - keep this file private.\nreturn " . var_export($config, true) . ";\n"
            );
            if ($written === false) {
                throw new RuntimeException('Could not write app/config.php. Give the app/ folder write permission (755) and try again.');
            }
            @chmod($configPath, 0640);
            Config::load($config);

            $existing = Database::value('SELECT id FROM users WHERE username = ?', [$username]);
            if ($existing === null) {
                if ($password === '') {
                    Database::run(
                        'INSERT INTO users (username, email, password_hash, role, must_change_password, created_at)
                         VALUES (?, ?, ?, ?, 1, NOW())',
                        [$username, $email, SEEDED_ADMIN_HASH, 'admin']
                    );
                } else {
                    Auth::createUser($username, $password, $email, false);
                }
            }

            Settings::put('schema_version', (string)Schema::VERSION);

            if (Settings::get('platform_name') === null) {
                Settings::put('platform_name', 'Chatbot Platform');
                Settings::put('default_chat_model', 'gpt-4o-mini');
                Settings::put('openai_base_url', 'https://api.openai.com/v1');
            }

            if (post('openai_api_key')) {
                Settings::put('openai_api_key', (string)post('openai_api_key'));
            }

            $done = true;
        } catch (Throwable $e) {
            $errors[] = $e->getMessage();
        }
    }
}
