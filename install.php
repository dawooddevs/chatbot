    <?php if ($alreadyInstalled): ?>
      <div class="alert success">
        This installation is already configured.
        <a href="index.php">Open the panel</a>.
      </div>
      <p class="muted">To reinstall, delete <span class="mono">app/config.php</span> first.
        For security, delete <span class="mono">install.php</span> from the server once you are done.</p>

    <?php elseif ($done): ?>
      <div class="alert success">Installation complete.</div>
      <p><strong>Two things left:</strong></p>
      <ol>
        <li>Delete <span class="mono">install.php</span> from the server.</li>
        <li>Sign in and add your OpenAI API key under Settings.</li>
      </ol>
      <a class="btn" href="index.php">Go to the panel</a>

    <?php else: ?>
      <?php foreach ($errors as $error): ?>
        <div class="alert error"><?= e($error) ?></div>
      <?php endforeach; ?>

      <h2 style="font-size:16px;margin-top:22px">Server check</h2>
      <table>
        <tbody>
        <?php foreach ($checks as $label => [$ok, $detail]): ?>
          <tr>
            <td><?= e($label) ?><br><span class="muted mono"><?= e((string)$detail) ?></span></td>
            <td class="right"><span class="badge <?= $ok ? 'green' : 'red' ?>"><?= $ok ? 'ok' : 'fix this' ?></span></td>
          </tr>
        <?php endforeach; ?>
        </tbody>
      </table>

      <form method="post" action="install.php" style="margin-top:24px">
        <h2 style="font-size:16px">Database</h2>
        <p class="muted" style="font-size:13px;margin-top:0">Create a database and user in cPanel → MySQL® Databases, give the user <em>all privileges</em>, then paste the details here.</p>
        <div class="field">
          <label for="db_host">Host</label>
          <input type="text" id="db_host" name="db_host" value="<?= e((string)post('db_host', 'localhost')) ?>">
        </div>
        <div class="field">
          <label for="db_name">Database name</label>
          <input type="text" id="db_name" name="db_name" value="<?= e((string)post('db_name', '')) ?>" placeholder="cpaneluser_chatbot" required>
        </div>
        <div class="field">
          <label for="db_user">Database user</label>
          <input type="text" id="db_user" name="db_user" value="<?= e((string)post('db_user', '')) ?>" placeholder="cpaneluser_chatbot" required>
        </div>
        <div class="field">
          <label for="db_pass">Database password</label>
          <input type="password" id="db_pass" name="db_pass" autocomplete="off">
        </div>
        <div class="field">
          <label for="db_port">Port</label>
          <input type="number" id="db_port" name="db_port" value="<?= e((string)post('db_port', '3306')) ?>">
        </div>

        <h2 style="font-size:16px;margin-top:22px">This installation</h2>
        <div class="field">
          <label for="base_url">Public URL</label>
          <input type="text" id="base_url" name="base_url" value="<?= e((string)post('base_url', $guessedBase)) ?>">
          <div class="help">Used to build the embed code.</div>
        </div>

        <h2 style="font-size:16px;margin-top:22px">Admin account</h2>
        <div class="field">
          <label for="admin_username">Username</label>
          <input type="text" id="admin_username" name="admin_username" value="<?= e((string)post('admin_username', SEEDED_ADMIN_USERNAME)) ?>" required>
        </div>
        <div class="field">
          <label for="admin_password">Password</label>
          <input type="password" id="admin_password" name="admin_password" autocomplete="new-password" minlength="10">
          <div class="help">Leave empty to keep the password that was already set up for <strong><?= e(SEEDED_ADMIN_USERNAME) ?></strong>; you will be asked to change it at first sign-in.</div>
        </div>
        <div class="field">
          <label for="admin_email">Email (optional)</label>
          <input type="email" id="admin_email" name="admin_email" value="<?= e((string)post('admin_email', '')) ?>">
        </div>

        <h2 style="font-size:16px;margin-top:22px">OpenAI (optional now)</h2>
        <div class="field">
          <label for="openai_api_key">API key</label>
          <input type="password" id="openai_api_key" name="openai_api_key" autocomplete="off" placeholder="sk-…">
          <div class="help">You can also add it later under Settings.</div>
        </div>

        <button class="btn" type="submit" style="width:100%;justify-content:center" <?= $checksPass ? '' : 'disabled' ?>>
          <?= $checksPass ? 'Install now' : 'Fix the items above first' ?>
        </button>
      </form>
    <?php endif; ?>
  </div>
</div>
